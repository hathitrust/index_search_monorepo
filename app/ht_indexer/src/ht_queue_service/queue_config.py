import copy
import dataclasses
from pathlib import Path
from typing import Any

import yaml
from ht_utils.ht_env_config import HtEnvConfig

# If we don't specify a max_message_size, we will use the default value of 16 MiB (16,777,216 bytes).
DEFAULT_MAX_MESSAGE_SIZE_BYTES = 16_777_216  # RabbitMQ 4.x default max_message_size (16 MiB)
RABBITMQ_MAX_MESSAGE_SIZE_BYTES = 536_870_912  # RabbitMQ hard maximum (512 MiB)
# batch_size is also passed to basic_qos as prefetch_count, a 16-bit AMQP field (0 would mean unlimited).
MAX_BATCH_SIZE = 65_535


@dataclasses.dataclass
class QueueParams:
    """Marshalls configuration from the environment and from YAML files to create connection parameters for rabbitmq"""

    host: str
    port: int
    user: str
    password: str
    # Parameters defining by each application
    queue_name: str
    batch_size: int
    requeue_message: bool
    exchange_type: str
    durable: bool
    auto_delete: bool
    exclusive: bool
    heartbeat: int
    connection_timeout: int
    retry_interval: int
    shutdown_on_empty_queue: bool
    # Parameters generated by the QueueConfig using the queue_name
    main_exchange_name: str  # Main exchange name
    dlx_exchange: str  # Dead-letter exchange name
    dlx_routing_key: str  # Dead-letter routing key
    dlx_queue_name: str  # Dead-letter queue name
    arguments: dict[str, Any]  # Can be provided by the user or generated by the QueueConfig
    # Used by the document indexer: how many times a message may be put back on the queue after
    # Solr answers its own request with a 5xx, before it is sent to the Dead Letter Queue.
    max_retries: int = 5
    max_message_size: int = (
        DEFAULT_MAX_MESSAGE_SIZE_BYTES  # bytes; must not exceed the broker's max_message_size
    )

def _load_config(config_path: Path) -> dict[str, Any]:
    with open(config_path) as file:
        return yaml.safe_load(file) or {}


class QueueConfig:
    def __init__(
        self, global_path: Path, app_path: Path, config_key: str = "queue", prefix: str = ""
    ) -> None:
        """
        Initialize the QueueConfig with default values or load from a YAML file.

        Environment variables are required for the host, port, username, and
        password; see HtEnvConfig for the list of RabbitMQ-specific environment
        variables.

        :param global_path: Path to the global YAML configuration file.
        :param app_path: Path to the application-specific YAML configuration file.
        :param config_key: Key to identify the specific queue configuration in the YAML files.
        :param prefix: Optional prefix for environment variables to initialize the queue configuration
        for document_generator service that has a source (_SRC) and target (_TGT) queues.
        """

        prefix = prefix.lower()
        self.env_mapping = {
            "host": f"rabbitmq_indexer_{prefix}rw_host",
            "port": f"rabbitmq_indexer_{prefix}rw_port",
            "user": f"rabbitmq_indexer_{prefix}rw_username",
            "password": f"rabbitmq_indexer_{prefix}rw_password",
        }

        default_global_config = _load_config(global_path)["queue"]

        # Load the global configuration
        global_cfg = self._load_env_vars(default_global_config)

        default_app_config = _load_config(app_path)[config_key]

        # Merge the configurations, with app_config taking precedence
        app_cfg = {**global_cfg, **default_app_config}

        # Load the application-specific configuration
        self.merged_config = self._load_env_vars(app_cfg)

        self.queue_params = QueueParams(**self._create_queue_params())

        size = self.queue_params.max_message_size
        if not 1 <= size <= RABBITMQ_MAX_MESSAGE_SIZE_BYTES:
            raise ValueError(
                f"max_message_size must be between 1 and {RABBITMQ_MAX_MESSAGE_SIZE_BYTES} bytes, got {size}"
            )

        batch_size = self.queue_params.batch_size
        if not 1 <= batch_size <= MAX_BATCH_SIZE:
            raise ValueError(f"batch_size must be between 1 and {MAX_BATCH_SIZE}, got {batch_size}")

    def _load_env_vars(self, config: dict[str, Any]) -> dict[str, Any]:
        queue_cfg = copy.deepcopy(config)
        env_config = HtEnvConfig()

        # Override with environment variables if they exist
        # Environment variables take precedence over config file values
        for key, attrname in self.env_mapping.items():
            env_value = getattr(env_config, attrname)
            if env_value is not None:
                queue_cfg[key] = int(env_value) if key == "port" else env_value

        return queue_cfg

    def _create_queue_params(self) -> dict[str, Any]:
        """
        Create and return a QueueParams object with the current configuration.
        """

        queue_cfg = copy.deepcopy(self.merged_config)

        queue_cfg["main_exchange_name"] = f"{queue_cfg['queue_name']}_exchange"
        # Apply DLX arguments
        queue_cfg["dlx_exchange"] = f"{queue_cfg['queue_name']}_dlx_exchange"
        queue_cfg["dlx_routing_key"] = f"dlx_key_{queue_cfg['queue_name']}"
        queue_cfg["dlx_queue_name"] = f"{queue_cfg['queue_name']}_dlq"

        # Ensure 'arguments' exists
        if self.merged_config.get("arguments", {}):
            queue_cfg["arguments"] = self.merged_config["arguments"]
        else:
            queue_cfg["arguments"] = {
                "x-dead-letter-exchange": queue_cfg["dlx_exchange"],
                "x-dead-letter-routing-key": queue_cfg["dlx_routing_key"],
            }

        return queue_cfg

    def get_params(self) -> QueueParams:
        return self.queue_params
